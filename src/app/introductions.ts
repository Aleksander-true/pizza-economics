export function notebookExamples(level: Level): NotebookRow[] {
  return [{ cheese: 2, olives: 1 }, { cheese: 1, olives: 2 }].map(({ cheese, olives }, index) => {
    const plan = evaluatePlan(level, [
      { id: 1, size: 15, portions: amounts([1,1,1]), quantity: cheese },
      { id: 2, size: 15, portions: amounts([1,1,1,1]), quantity: olives },
    ]);
    return { id: index + 1, pizzas: `${cheese} с сыром 15 см\n${olives} с оливками 15 см`, profit: String(plan.profit) };
  });
}
