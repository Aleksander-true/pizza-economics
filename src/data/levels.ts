export const LEVELS: readonly LevelDefinition[] = definitions.map((definition, index) => {
  const day = index + 1;
  const sizes: readonly PizzaSize[] = day <= 2 ? [15] : day < 10 ? [15,30] : [15,30,45];
  const recipeCount = day < 4 ? 2 : day < 9 ? 3 : 4;
  const recipes = RECIPES.slice(0, recipeCount);
  return {
    id: day, title: definition.title, lesson: definition.lesson, tip: definition.tip, hints: definition.hints,
    delivery: amounts(definition.delivery), costs: amounts([1,1,1,1,2,2]), sizes,
    ingredientIds: INGREDIENTS.slice(0, recipeCount + 2).map(item => item.id), recipes,
    offers: recipes.flatMap((recipe, recipeIndex) => sizes.map(size => ({
      recipeId: recipe.id, size, price: smallPrices[recipeIndex] * SIZE_FACTORS[size] - sizeDiscount[size],
    }))),
  };
});
